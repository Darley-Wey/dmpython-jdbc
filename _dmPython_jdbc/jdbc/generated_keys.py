"""Read the key an INSERT generated from its own JDBC statement."""

RETURN_GENERATED_KEYS = 1  # java.sql.Statement.RETURN_GENERATED_KEYS


class GeneratedKeysJdbc:
    """Stands in for the JDBC connection while one INSERT is prepared.

    jaydebeapi always calls prepareStatement(sql), and DM only reports the key
    an INSERT generated when the statement was prepared asking for it.
    """

    def __init__(self, jconn):
        self._jconn = jconn

    def prepareStatement(self, sql):
        return self._jconn.prepareStatement(sql, RETURN_GENERATED_KEYS)


def generated_key(prepared):
    """Key generated by the INSERT just executed on `prepared`, else None.

    DM reports IDENTITY and AUTO_INCREMENT values in an AUTO_GEN_KEY column,
    one row per inserted row. An INSERT that generated none (no such column, or
    IDENTITY_INSERT) gets a placeholder ROWID row; INSERT ... SELECT gets no rows.
    Unlike SCOPE_IDENTITY() and LAST_INSERT_ID(), which each cover only one of
    the two column kinds and keep the value of an earlier INSERT, this belongs
    to the statement itself.
    """
    try:
        keys = prepared.getGeneratedKeys()
        try:
            if str(keys.getMetaData().getColumnLabel(1)).upper() != "AUTO_GEN_KEY":
                return None
            key = None
            while keys.next():
                key = int(keys.getLong(1))
            return key
        finally:
            keys.close()
    except Exception:
        return None
